using System.IO;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;

namespace DigitalJeeves.MsAccessMCP.Core;

/// <summary>
/// Loads the canonical <c>VbaTestKit.bas</c> (shared with VbaTestHost) and renders it for a scratch
/// database, and generates the Access-side test runner module.
/// </summary>
internal static class VbaTestKit
{
    public const string ModuleName = "VbaTestKit";
    public const string ResultPathToken = "@RESULT_PATH@";
    public const string RunnerModuleName = "AccessMcpTestRunner";
    public const string RunnerEntryPoint = "RunAllTests";

    private const string ResourceName = "AccessMCP.Resources.VbaTestKit.bas";

    private static readonly Lazy<string> Template = new(LoadTemplate);

    /// <summary>The kit source with the @RESULT_PATH@ token intact.</summary>
    public static string Source => Template.Value;

    /// <summary>SHA-256 of the kit source, used in the MDE cache key and diagnostics.</summary>
    public static string Sha256 => VbaProjectEditor.Sha256Hex(Source);

    /// <summary>Renders the kit with an absolute NDJSON result path for this scenario.</summary>
    public static string Render(string resultPath)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(resultPath);
        return Source.Replace(ResultPathToken, EscapeVbaString(Path.GetFullPath(resultPath)), StringComparison.Ordinal);
    }

    /// <summary>
    /// Generates <c>AccessMcpTestRunner</c>. Each test is invoked with an unqualified
    /// <c>Application.Run</c> name (Access rejects "Module.Procedure") inside its own error handler,
    /// and every start/outcome is appended to the kit's NDJSON file so a crash or hang still leaves
    /// the results written so far.
    /// </summary>
    public static string GenerateRunner(IReadOnlyList<(string Module, VbaProcedureInfo Procedure)> tests)
    {
        var duplicate = tests
            .GroupBy(t => t.Procedure.Name, StringComparer.OrdinalIgnoreCase)
            .FirstOrDefault(g => g.Count() > 1);
        if (duplicate is not null)
        {
            throw new InvalidOperationException(
                $"Duplicate '@test procedure name '{duplicate.Key}' in " +
                string.Join(", ", duplicate.Select(d => d.Module)) +
                ". Access resolves calls by procedure name, so test names must be unique.");
        }

        var runnable = tests
            .Where(t => !t.Procedure.IsSkipped && IsRunnable(t.Procedure))
            .ToArray();

        var skipped = tests
            .Where(t => t.Procedure.IsSkipped)
            .ToArray();

        var unsupported = tests
            .Where(t => !t.Procedure.IsSkipped && !IsRunnable(t.Procedure))
            .ToArray();

        var builder = new StringBuilder();
        builder.AppendLine("Option Explicit");
        builder.AppendLine();
        builder.AppendLine("' Generated by AccessMCP. Do not edit - it is rewritten for every run.");
        builder.AppendLine("' Tests are called directly (not through Application.Run, which lets VBA show");
        builder.AppendLine("' a modal error dialog instead of returning the error to the caller).");
        builder.AppendLine();
        builder.AppendLine("Private Const TestSeparator As String = vbNullChar");
        builder.AppendLine();
        builder.AppendLine("Public Function " + RunnerEntryPoint + "() As String");

        foreach (var test in skipped)
        {
            builder.AppendLine("    EmitResult " + VbaString(test.Procedure.Name) + ", \"skip\", \"\"");
        }

        foreach (var test in unsupported)
        {
            builder.AppendLine("    EmitResult " + VbaString(test.Procedure.Name) + ", \"skip\", \"Unsupported test procedure kind: " +
                test.Procedure.Kind.Replace("\"", "\"\"") + "\"");
        }

        foreach (var test in runnable)
        {
            var name = test.Procedure.Name;
            var expected = test.Procedure.IsExpectedFailure;

            builder.AppendLine();
            builder.AppendLine("    EmitResult " + VbaString(name) + ", \"start\", \"\"");
            builder.AppendLine("    On Error Resume Next");
            builder.AppendLine("    Err.Clear");
            builder.AppendLine("    Call " + name);
            builder.AppendLine("    If Err.Number = 0 Then");
            builder.AppendLine(expected
                ? "        EmitResult " + VbaString(name) + ", \"xpass\", \"\""
                : "        EmitResult " + VbaString(name) + ", \"pass\", \"\"");
            builder.AppendLine("    ElseIf Err.Number = vbObjectError + 2001 Then");
            builder.AppendLine(expected
                ? "        EmitResult " + VbaString(name) + ", \"xfail\", Err.Description"
                : "        EmitResult " + VbaString(name) + ", \"fail\", Err.Description");
            builder.AppendLine("    Else");
            builder.AppendLine("        EmitResult " + VbaString(name) + ", \"error\", CStr(Err.Number) & \" \" & Err.Description");
            builder.AppendLine("    End If");
            builder.AppendLine("    On Error GoTo 0");
        }

        builder.AppendLine();
        builder.AppendLine("    " + RunnerEntryPoint + " = \"done\"");
        builder.AppendLine("End Function");
        builder.AppendLine();
        builder.AppendLine("Private Sub EmitResult(ByVal testName As String, ByVal outcome As String, ByVal detail As String)");
        builder.AppendLine("    Dim text As String");
        builder.AppendLine("    text = Replace(CStr(detail), vbCrLf, \" \")");
        builder.AppendLine("    text = Replace(text, vbCr, \" \")");
        builder.AppendLine("    text = Replace(text, vbLf, \" \")");
        builder.AppendLine("    text = Replace(text, TestSeparator, \" \")");
        builder.AppendLine("    VbaTestKit.Log \"@@test\" & TestSeparator & outcome & TestSeparator & testName & TestSeparator & CStr(CLng(Timer() * 1000)) & TestSeparator & text");
        builder.AppendLine("End Sub");

        return builder.ToString();
    }

    private static bool IsRunnable(VbaProcedureInfo procedure)
        => procedure.Kind.Equals("Sub", StringComparison.OrdinalIgnoreCase) ||
           procedure.Kind.Equals("Function", StringComparison.OrdinalIgnoreCase);

    /// <summary>Escapes a string as a VBA string literal (without the Attribute header).</summary>
    public static string VbaString(string value) => "\"" + value.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";

    private static string EscapeVbaString(string value) => value.Replace("\"", "\"\"", StringComparison.Ordinal);

    private static string LoadTemplate()
    {
        using var stream = Assembly.GetExecutingAssembly().GetManifestResourceStream(ResourceName)
            ?? throw new InvalidOperationException($"Embedded resource '{ResourceName}' is missing.");

        using var reader = new StreamReader(stream, Encoding.UTF8, detectEncodingFromByteOrderMarks: true);
        return reader.ReadToEnd();
    }
}
