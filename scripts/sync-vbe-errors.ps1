#requires -Version 7.0
<#
.SYNOPSIS
    Syncs the canonical VBE compile-error table from ~/vbe7 into AccessMCP.

.DESCRIPTION
    The canonical source is VbeCompileErrors.json in the VBE7 research repository:
        C:\Users\<user>\vbe7\VbeCompileErrors.json
    It is generated by:
        pwsh ./scripts/build-compile-error-table.ps1
        pwsh ./scripts/make-compact-table.ps1

    AccessMCP embeds the compact JSON as AccessMCP.Resources.VbeCompileErrors.json.

.PARAMETER Source
    Canonical VbeCompileErrors.json.

.PARAMETER Target
    Embedded resource in AccessMCP.Core/Resources.

.PARAMETER Check
    Exit non-zero if the target is missing or differs from the source.

.EXAMPLE
    pwsh ./scripts/sync-vbe-errors.ps1 -Check
    pwsh ./scripts/sync-vbe-errors.ps1
#>
[CmdletBinding()]
param(
    [string]$Source = (Join-Path $env:USERPROFILE 'vbe7\VbeCompileErrors.json'),
    [string]$Target = (Join-Path $PSScriptRoot '..\AccessMCP.Core\Resources\VbeCompileErrors.json'),
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$Source = [System.IO.Path]::GetFullPath($Source)
$Target = [System.IO.Path]::GetFullPath($Target)

if (-not (Test-Path $Source)) { throw "Canonical table not found: $Source" }

$sourceHash = (Get-FileHash $Source -Algorithm SHA256).Hash
if (-not (Test-Path $Target)) {
    if ($Check) {
        Write-Error "Missing $Target. Run: pwsh ./scripts/sync-vbe-errors.ps1"
        exit 1
    }
    $targetHash = $null
}
else {
    $targetHash = (Get-FileHash $Target -Algorithm SHA256).Hash
}

if ($Check) {
    if ($sourceHash -ne $targetHash) {
        Write-Error "VBE compile-error table is stale. Run: pwsh ./scripts/sync-vbe-errors.ps1"
        exit 1
    }
    Write-Host "VBE compile-error table is in sync ($sourceHash)."
    exit 0
}

if ($sourceHash -eq $targetHash) {
    Write-Host "VBE compile-error table already in sync ($sourceHash)."
    exit 0
}

$dir = Split-Path -Parent $Target
if ($dir) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
Copy-Item -Path $Source -Destination $Target -Force
Write-Host "Copied $Source -> $Target ($sourceHash)"
